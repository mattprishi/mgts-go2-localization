"""Write the tables from metrics.py as a compact Russian report."""
from math import isfinite
from os.path import relpath
import shlex


LABELS = {"odometry": "Одометрия", "full_icp": "ICP, полная поправка", "smooth_icp": "ICP, сглаживание",
          "baseline_ekf": "Базовый старт + EKF (2,5°)", "multiview_ekf": "Старт по нескольким видам + EKF (2,5°)",
          "baseline_ekf_4": "Базовый старт + EKF (4°)", "multiview_ekf_4": "Старт по нескольким видам + EKF (4°)",
          "multiview_icp": "Старт по нескольким видам + сглаженный ICP"}
BLOCKS = {"development": "5–45 с, разработка", "buffer": "45–65 с, буфер", "temporal_check": "С 65 с, временная проверка"}


def fmt(value, digits=2):
    return f"{value:.{digits}f}" if value is not None and isfinite(value) else "—"


def write_report(path, rows, methods, observers, anchor, target, cache, raw_frames, yaw_sources, obs_rows):
    full = [r for r in rows if r["window"] == "full"]
    def label(row):
        name = row["method"]
        return LABELS.get(name, name)
    timing_count = max(r["paired_ros_scans"] for r in full)
    lines = [
        "# Проверка локализации на втором проходе",
        "",
        "Карту строим по первому проходу. Во втором проходе измеряем, как точки очередного скана ложатся на карту при последней известной поправке. Все методы сравниваются по одинаковым меткам времени. Точность положения робота в метрах остаётся неизвестной.",
        "",
        f"## Сравнение на {full[0]['paired_scans']} общих сканах",
        "",
        (f"Геометрия оценена на {full[0]['paired_scans']} сканах, поправки между соседними позами — на {full[0]['jump_pairs']} переходах. "
         + (f"Задержка сопоставлена по {timing_count} общим меткам. " if timing_count else "")
         + "Покрытие учитывает весь входной поток, включая старт."),
        "",
        f"| Метод | Первая поза, с | Поз / {full[0]['total_input']} | Точки ≤20 см, % ↑ | Расстояние, см ↓ | Скачки | Слабые эпизоды | RMS ускорения XY, м/с² | P95, мс / случаев >72 мс |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in full:
        latency = f"{fmt(r['ros_p95_ms'])} / {r['ros_over_72_ms']}" if r["paired_ros_scans"] else "—"
        lines.append(f"| {label(r)} | {fmt(r['first_pose_s'],3)} | {r['total_poses']} | {fmt(100*r['overlap'])} | {fmt(100*r['clipped_distance_m'])} | {r['jump_either_n']} | {r['weak_geometry_episodes']} | {fmt(r['xy_accel_rms_m_s2'],3)} | {latency} |")
    lines += [
        "",
        "| Метод | Скачки XY / курса | Без принятой поправки LiDAR, кадры / максимум, с | Пропуски после первой позы | Длина XY, м | RMS углового ускорения, °/с² |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for r in full:
        fallback = "—" if r["fallback_frames"] is None else f"{r['fallback_frames']} / {fmt(r['fallback_max_s'])}"
        lines.append(f"| {label(r)} | {r['jump_translation_n']} / {r['jump_yaw_n']} | {fallback} | {r['missed_poses_after_lock']} | {fmt(r['xy_length_m'])} | {fmt(r['yaw_accel_rms_deg_s2'],2)} |")
    lines += [
        "", "## Участки одного маршрута", "",
        "Первые 5 с отводятся на старт. Общие кадры после привязки до 5 с входят в сводную таблицу выше. Параметры выбираются на 5–45 с. Буфер 45–65 с включает известный поворот на 50–55 с. После фиксации параметров сравниваем методы с 65 с до конца. Эти данные ранее просматривались. Независимого тестового маршрута и эталонной траектории у нас нет.",
        "",
        "| Интервал | Метод | Общие кадры | Точки ≤20 см, % | Среднее расстояние, см |",
        "|---|---|---:|---:|---:|",
    ]
    for r in rows:
        if r["window"] in BLOCKS:
            lines.append(f"| {BLOCKS[r['window']]} | {label(r)} | {r['paired_scans']} | {fmt(100*r['overlap'])} | {fmt(100*r['clipped_distance_m'])} |")
    if observers:
        lines += [
            "", "## Задержка на воспроизведении 1×", "",
            "Отдельный ROS-наблюдатель измерял время от получения облака до получения позы по одной метке. В таблице приведено пересечение наблюдаемых меток всех измеренных методов с основными парными строками. Для каждой записи полные замеры, включая инициализацию, находятся в [observer_all.csv](observer_all.csv). 72 мс соответствует медианному периоду входных сканов. Запуски с разными конфигурациями QoS меняют условия доставки, поэтому разность задержек нельзя целиком приписать алгоритму.",
            "",
            "| Метод | Общие замеры | P50, мс | P95, мс | P99, мс | Макс., мс | >72 мс |",
            "|---|---:|---:|---:|---:|---:|---:|",
        ]
        for r in full:
            if r["method"] in observers:
                lines.append(f"| {label(r)} | {r['paired_ros_scans']} | {fmt(r['ros_p50_ms'])} | {fmt(r['ros_p95_ms'])} | {fmt(r['ros_p99_ms'])} | {fmt(r['ros_max_ms'])} | {r['ros_over_72_ms']} |")
        lines += ["", "Полный прогон каждого метода включает первую опубликованную позу и все последующие измеренные кадры.",
                  "", "| Метод | Превышений 72 мс / измеренных поз | P95, мс | Макс., мс |",
                  "|---|---:|---:|---:|"]
        for r in obs_rows:
            lines.append(f"| {label(r)} | {r['over_72_ms']} / {r['matched']} | {fmt(r['p95_ms'])} | {fmt(r['max_ms'])} |")
    lines += [
        "", "## Определения", "",
        "- Для скана с меткой t применяем преобразование map←odom, которое метод выдал на предыдущем скане. Входной cloud_deskewed уже выражен в локальной системе odom. Поэтому текущий скан впервые участвует в расчёте после того, как определено проверяемое преобразование. Внутренний прогноз отдельного фильтра может дополнительно учитывать собственную скорость дрейфа.",
        "- Для точек скана с высотой 0,30 < z < 2,00 м находим ближайшую точку карты с 0,15 < z < 2,20 м в 3D. На каждом кадре считаем долю расстояний ≤0,20 м и среднее расстояние с ограничением сверху 0,40 м. В итоговом среднем у каждого скана одинаковый вес. Эти числа характеризуют геометрическое совпадение. Абсолютная ошибка позы по ним неизвестна.",
        ("- Для одометрии используем отдельный прогон ROS с фиксированной привязкой. "
         if raw_frames else "- Одометрия использует постоянную первую привязку базового ICP из файла anchor. ")
        + "При разных инициализациях на совпадение с картой влияют и стартовая привязка, и последующие поправки. Покрытие и время первой позы считаем по всей записи.",
        "- Скачок — горизонтальная поправка позиции корпуса более 5 см или изменение коррекции курса более 1° за входной скан. Из позиции вычитаем положение того же корпуса по свежей одометрии с предыдущим map←odom. Для одометрии поправка равна нулю по определению. Это диагностические пороги команды.",
        "- Число в скобках у EKF — принятое стандартное отклонение ошибки измерения курса по ICP. При 4° фильтр слабее доверяет повороту, предложенному сканом, чем при 2,5°.",
        "- Эпизод слабого совпадения — непрерывное overlap <0,50 не менее 0,50 с. У каждого кадра состояние действует до следующей метки, на последнем кадре интервал закрывается, при разрыве >0,20 с берём типичный шаг и прерываем эпизод. Отдельно считаем статус odometry, когда алгоритм выдаёт позу без принятой поправки текущего скана. В EKF при этом сохраняется собственный прогноз. Отметки считаем на общих валидных позах после стартовой привязки, включая случаи без пригодных для проверки точек. Для скачков нужны две соседние доступные позы с интервалом до 0,20 с. Физическая потеря робота по этим признакам не установлена.",
        "- Длину пути и RMS горизонтального и углового ускорения считаем на сетке 0,5 с, начиная с ближайшего общего узла. Позицию и развёрнутый курс линейно интерполируем внутри непрерывных отрезков с доступными позами. Ускорение — центральная вторая разность. В RMS входят и естественные манёвры. Меньшее ускорение указывает на более плавный оценённый путь. Даже чрезмерно сглаженная или смещённая траектория может дать малый RMS.",
        ("- Для горизонтальной кинематики берём фактические позиции из файлов методов. При отсутствии отдельного прогона одометрии восстанавливаем её позицию по входному кешу. "
         + ("Опубликованный курс доступен у следующих методов: " + ", ".join(LABELS.get(n,n) for n in yaw_sources) + ". " if yaw_sources else "")
         + ("В остальных случаях курс вычислен из кватерниона одометрии в кеше и поворота map←odom." if len(yaw_sources) < len(methods) else "")),
        "- Пустые инициализационные строки и сканы без геометрии исключаются из соответствующего парного показателя. Все входные метки, включая исключённые, остаются в [paired_frames.csv](paired_frames.csv). Все показатели и временные окна доступны в [comparison.csv](comparison.csv).",
        "", "## Воспроизведение", "", "Команда запуска из корня проекта", "", "```sh",
    ]
    command = ["python3", "analysis/validation/metrics.py", "--anchor", str(anchor), "--map", str(target), "--cache", str(cache), "--out", str(path.parent)]
    if raw_frames:
        command += ["--raw-frames", str(raw_frames)]
    for name, source in methods.items():
        if name != "odometry":
            command += ["--method", f"{name}={source}"]
    for name, source in observers.items():
        command += ["--observer", f"{name}={source}"]
    lines += [shlex.join(command), "```", "", f"[Код метрик]({relpath('analysis/validation/metrics.py',path.parent)})"]
    path.write_text("\n".join(lines)+"\n")
